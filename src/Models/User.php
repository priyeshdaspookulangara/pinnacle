<?php
// src/Models/User.php

require_once __DIR__ . '/../../config/database.php';

class User {
    private PDO $db;

    public function __construct() {
        $this->db = Database::getConnection();
    }

    public function findById(int $id): ?array {
        $stmt = $this->db->prepare("SELECT * FROM users WHERE id = ?");
        $stmt->execute([$id]);
        $user = $stmt->fetch();
        return $user ?: null;
    }

    public function findByUsername(string $username): ?array {
        $stmt = $this->db->prepare("SELECT * FROM users WHERE username = ?");
        $stmt->execute([$username]);
        $user = $stmt->fetch();
        return $user ?: null;
    }

    public function findByEmail(string $email): ?array {
        $stmt = $this->db->prepare("SELECT * FROM users WHERE email = ?");
        $stmt->execute([$email]);
        $user = $stmt->fetch();
        return $user ?: null;
    }

    public function register(string $username, string $email, string $password, string $fullName, ?string $phone, ?int $sponsorId): int {
        $hash = password_hash($password, PASSWORD_BCRYPT);
        $stmt = $this->db->prepare("
            INSERT INTO users (username, email, password, full_name, phone, role, sponsor_id, wallet_balance, reserve_balance, status)
            VALUES (?, ?, ?, ?, ?, 'user', ?, 0.00, 0.00, 'active')
        ");
        $stmt->execute([$username, $email, $hash, $fullName, $phone, $sponsorId]);
        return (int)$this->db->lastInsertId();
    }

    public function authenticate(string $login, string $password): ?array {
        $stmt = $this->db->prepare("SELECT * FROM users WHERE username = ? OR email = ?");
        $stmt->execute([$login, $login]);
        $user = $stmt->fetch();

        if ($user && password_verify($password, $user['password'])) {
            return $user;
        }
        return null;
    }

    public function updateBalances(int $userId, float $walletDelta, float $reserveDelta): bool {
        $stmt = $this->db->prepare("
            UPDATE users
            SET wallet_balance = wallet_balance + ?, reserve_balance = reserve_balance + ?
            WHERE id = ?
        ");
        return $stmt->execute([$walletDelta, $reserveDelta, $userId]);
    }

    public function getAllUsers(): array {
        $stmt = $this->db->query("
            SELECT u.*, s.username as sponsor_username
            FROM users u
            LEFT JOIN users s ON u.sponsor_id = s.id
            ORDER BY u.id DESC
        ");
        return $stmt->fetchAll();
    }

    public function updateMember(int $id, string $fullName, string $email, ?string $phone, float $walletBalance, float $reserveBalance, string $status, ?string $newPassword = null): bool {
        if (!empty($newPassword)) {
            $hash = password_hash($newPassword, PASSWORD_BCRYPT);
            $stmt = $this->db->prepare("
                UPDATE users
                SET full_name = ?, email = ?, phone = ?, wallet_balance = ?, reserve_balance = ?, status = ?, password = ?
                WHERE id = ?
            ");
            return $stmt->execute([$fullName, $email, $phone, $walletBalance, $reserveBalance, $status, $hash, $id]);
        } else {
            $stmt = $this->db->prepare("
                UPDATE users
                SET full_name = ?, email = ?, phone = ?, wallet_balance = ?, reserve_balance = ?, status = ?
                WHERE id = ?
            ");
            return $stmt->execute([$fullName, $email, $phone, $walletBalance, $reserveBalance, $status, $id]);
        }
    }

    public function deleteMemberCompletely(int $userId): bool {
        // Prevent deleting admin #1
        if ($userId === 1) {
            throw new Exception("The primary administrator account cannot be deleted.");
        }

        $user = $this->findById($userId);
        if (!$user) {
            throw new Exception("Member not found.");
        }

        $this->db->beginTransaction();
        try {
            // 1. Revert all commissions where this user was the source_user_id (earnings paid to uplines)
            // Retrieve all commissions generated by this user to uplines
            $stmtComm = $this->db->prepare("SELECT * FROM commissions WHERE source_user_id = ?");
            $stmtComm->execute([$userId]);
            $commissionsGenerated = $stmtComm->fetchAll();

            foreach ($commissionsGenerated as $comm) {
                $recipientId = (int)$comm['user_id'];
                if ($recipientId !== $userId) { // If paid to someone else
                    $netDeduct = (float)$comm['net_amount'];
                    $resDeduct = (float)$comm['reserved_amount'];

                    // Deduct from recipient balances (ensure not negative, or floor to 0)
                    $stmtUpdateUpline = $this->db->prepare("
                        UPDATE users
                        SET wallet_balance = GREATEST(0.00, wallet_balance - ?),
                            reserve_balance = GREATEST(0.00, reserve_balance - ?)
                        WHERE id = ?
                    ");
                    $stmtUpdateUpline->execute([$netDeduct, $resDeduct, $recipientId]);

                    // Add an audit ledger entry for the clawback
                    $stmtUplineData = $this->db->prepare("SELECT wallet_balance, reserve_balance FROM users WHERE id = ?");
                    $stmtUplineData->execute([$recipientId]);
                    $uplineNow = $stmtUplineData->fetch();

                    if ($uplineNow) {
                        $stmtLedger = $this->db->prepare("
                            INSERT INTO ledger (user_id, type, amount, balance_after, reserve_after, description)
                            VALUES (?, 'debit', ?, ?, ?, ?)
                        ");
                        $clawbackDesc = "Clawback: Deleted member @" . $user['username'] . " commission reversed (#" . $comm['id'] . ")";
                        $stmtLedger->execute([$recipientId, ($netDeduct + $resDeduct), $uplineNow['wallet_balance'], $uplineNow['reserve_balance'], $clawbackDesc]);
                    }
                }
            }

            // 2. Decrement children_count of parent matrix nodes for all nodes owned by this user
            $stmtUserNodes = $this->db->prepare("SELECT id, package_id, parent_id FROM matrix_nodes WHERE user_id = ?");
            $stmtUserNodes->execute([$userId]);
            $userNodes = $stmtUserNodes->fetchAll();

            foreach ($userNodes as $node) {
                if (!empty($node['parent_id'])) {
                    $stmtDecr = $this->db->prepare("
                        UPDATE matrix_nodes
                        SET children_count = GREATEST(0, children_count - 1)
                        WHERE id = ?
                    ");
                    $stmtDecr->execute([$node['parent_id']]);
                }
            }

            // 3. Clear/re-link direct sponsor references of sponsored users to null (or admin)
            $stmtUpdateSponsored = $this->db->prepare("UPDATE users SET sponsor_id = NULL WHERE sponsor_id = ?");
            $stmtUpdateSponsored->execute([$userId]);

            // 4. Delete the user (ON DELETE CASCADE handles user_packages, commissions where user_id or source_user_id = $userId, withdrawals, ledger, and matrix_nodes)
            $stmtDelete = $this->db->prepare("DELETE FROM users WHERE id = ?");
            $stmtDelete->execute([$userId]);

            $this->db->commit();
            return true;
        } catch (Exception $e) {
            $this->db->rollBack();
            throw $e;
        }
    }
}
